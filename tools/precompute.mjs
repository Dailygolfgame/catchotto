// Picks hard daily boards offline and stores them in data/boards.js.
//   node tools/precompute.mjs            fill missing days up to 400 days ahead + practice pool
//   DAYS=730 node tools/precompute.mjs   look further ahead
// Only boards where no simulated player gets close to Perfect are kept.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { bestExcess } from './difficulty.mjs';
const require = createRequire(import.meta.url);
const C = require('../engine.js');
let data = { days: {}, pool: {} };
try { data = require('../data/boards.js'); } catch (e) { /* first run */ }

const FROM = '2026-11-06';
// Moves over Perfect that the best simulated player must at least need. Infinity: none catches Otto.
const NEED = { Easy: 1, Medium: 2, Hard: 3, Expert: Infinity };
const DAYS = +(process.env.DAYS || 400);
const POOL = +(process.env.POOL || 60);

function hardBoard(prefix, level) {
  for (let attempt = 0; attempt < 400; attempt++) {
    const pz = C.generate(C.hashString(`${prefix}:${attempt}`), level);
    const r = bestExcess(pz);
    if (r.best >= NEED[level.name]) return pz;
  }
  throw new Error('no hard board for ' + prefix);
}

const t0 = Date.now(); let added = 0;
const today = new Date().toISOString().slice(0, 10);
const until = new Date(Date.parse(today + 'T12:00:00Z') + DAYS * 864e5).toISOString().slice(0, 10);
for (let t = Date.parse(FROM + 'T12:00:00Z'); ; t += 864e5) {
  const ds = new Date(t).toISOString().slice(0, 10);
  if (ds > until) break;
  if (data.days[ds]) continue;
  data.days[ds] = C.encode(hardBoard('otto-v3:' + ds, C.dailyLevel(ds)));
  if (++added % 25 === 0) console.error(`${added} days… ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}
const LV = { Easy: 1, Medium: 3, Hard: 5, Expert: 6 };
for (const name of Object.keys(LV)) {
  data.pool[name] = data.pool[name] || [];
  for (let k = data.pool[name].length; k < POOL; k++) data.pool[name].push(C.encode(hardBoard(`otto-pool:${name}:${k}`, C.LEVELS[LV[name]])));
}
const out = `/* Generated by tools/precompute.mjs. Daily boards from ${FROM} and a practice pool. */
(function (root) {
  var data = ${JSON.stringify(data)};
  if (typeof module !== 'undefined' && module.exports) module.exports = data; else root.OTTO_BOARDS = data;
})(typeof window !== 'undefined' ? window : globalThis);
`;
writeFileSync(new URL('../data/boards.js', import.meta.url), out);
console.error(`added ${added} days, ${Object.keys(data.days).length} total, pool ${Object.values(data.pool).map((l) => l.length).join('/')}, ${((Date.now() - t0) / 1000).toFixed(0)}s, ${(out.length / 1024).toFixed(0)} KB`);
